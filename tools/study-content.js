// Study content converter (card MBA-ST12). Reads the curriculum project's CLEP slice and writes the two files the study page loads:
//   knowledge/mba/study/clep-fa-slice/items.json -> core/study/items-clep.js   (StudyItemsClep = { items: [{ id, concept, forms: { A, B, C } }] })
//   knowledge/mba/study/clep-fa-slice/reading.md -> core/study/reading-clep.js (StudyReadingClep = { SECTIONS: [{ id, title, text }] })
// Run: node tools/study-content.js          (writes both files)
//      node tools/study-content.js --check  (exit 1 if a written file differs from a fresh conversion)
// The sources live in the Agent System, outside this repo, so CI cannot run the check (tests/test-study-content.js skips it there).
const fs = require("fs"), path = require("path");

const SRC = path.join(__dirname, "..", "..", "..", "..", "knowledge", "mba", "study", "clep-fa-slice");
const OUT = path.join(__dirname, "..", "core", "study");
const FORMS = ["A", "B", "C"], LETTERS = ["A", "B", "C", "D", "E"];

// One bank item per concept: the first item of each concept on each form. Forms B and C hold a second item for S3 and S10
// that form A lacks; the page needs the same items on every form (pre and post test must compare), so those four are left out.
function convertItems(json) {
  const byConcept = {};
  for (const it of json.items) {
    const slot = byConcept[it.concept] || (byConcept[it.concept] = {});
    if (!slot[it.form]) slot[it.form] = it; // first one wins
  }
  const concepts = Object.keys(byConcept).sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));
  const items = concepts.map(c => {
    const forms = {};
    for (const f of FORMS) {
      const x = byConcept[c][f];
      if (!x) throw new Error("concept " + c + " has no item on form " + f);
      const letters = LETTERS.filter(l => x.options[l] !== undefined);
      if (letters.indexOf(x.key) < 0) throw new Error(x.id + " key " + x.key + " is not an option");
      forms[f] = { stem: x.stem, options: letters.map(l => x.options[l]), answer: letters.indexOf(x.key), source: x.id };
    }
    return { id: c, concept: c, forms };
  });
  return { items };
}

// Learner text: drop the internal "Source." paragraph and the markdown marks; keep blank lines between paragraphs.
function convertReading(md) {
  const parts = md.split(/^## (S\d+) (.*)$/m); // [preface, id, title, body, id, title, body, ...]
  const sections = [];
  for (let i = 1; i < parts.length; i += 3) {
    const paras = parts[i + 2].split(/\n\s*\n/).map(p => p.trim()).filter(p => p && !/^\*\*Source\.\*\*/.test(p));
    sections.push({ id: parts[i], title: parts[i + 1].trim(), text: paras.join("\n\n").replace(/\*\*/g, "").replace(/`/g, "") });
  }
  return { SECTIONS: sections };
}

const wrap = (global, doc, data) =>
  "// GENERATED by tools/study-content.js from " + doc + ". Do not edit by hand: run `node tools/study-content.js`.\n" +
  "(function (root) {\n  const api = " + JSON.stringify(data, null, 1).replace(/\n/g, "\n  ") + ";\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = api; else root." + global + " = api;\n" +
  "})(typeof window !== \"undefined\" ? window : globalThis);\n";

function build() {
  const items = convertItems(JSON.parse(fs.readFileSync(path.join(SRC, "items.json"), "utf8")));
  const reading = convertReading(fs.readFileSync(path.join(SRC, "reading.md"), "utf8").replace(/\r\n/g, "\n"));
  return {
    "items-clep.js": wrap("StudyItemsClep", "knowledge/mba/study/clep-fa-slice/items.json", items),
    "reading-clep.js": wrap("StudyReadingClep", "knowledge/mba/study/clep-fa-slice/reading.md", reading),
  };
}

module.exports = { SRC, OUT, convertItems, convertReading, build };

if (require.main === module) {
  const files = build(), check = process.argv.includes("--check");
  let bad = 0;
  for (const name of Object.keys(files)) {
    const file = path.join(OUT, name);
    if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== files[name]) { console.log("DRIFT " + name); bad++; } }
    else { fs.writeFileSync(file, files[name]); console.log("wrote " + name); }
  }
  process.exit(bad ? 1 : 0);
}
